#!/usr/bin/env python3
"""Embed the offline setup UI in flash; no filesystem partition upload needed."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ASSETS = [('index.html', 'text/html; charset=utf-8'), ('style.css', 'text/css; charset=utf-8'),
          ('app.mjs', 'text/javascript; charset=utf-8'), ('model.mjs', 'text/javascript; charset=utf-8'),
          ('device.mjs', 'text/javascript; charset=utf-8')]

def generate():
    lines = ['// Generated by scripts/embed-web.py. Edit web/ sources instead.', '#pragma once',
             '#include <Arduino.h>', 'namespace midi_cont { namespace web_assets {']
    for index, (name, _) in enumerate(ASSETS):
        content = (ROOT / 'web' / name).read_text()
        if ')MC4ASSET"' in content:
            raise ValueError('Raw string delimiter collision in ' + name)
        lines.append('static const char Asset%d[] PROGMEM = R"MC4ASSET(%s)MC4ASSET";' % (index, content))
    lines.append('} }\n')
    destination = ROOT / 'firmware/MIDICont/src/web/WebAssets.generated.h'
    content = '\n'.join(lines)
    if not destination.exists() or destination.read_text() != content:
        destination.write_text(content)

if __name__ == '__main__':
    generate()
